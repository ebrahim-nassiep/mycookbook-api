// Function to get a random image for a category
export const getRandomFoodImage = (category) => {
  const normalizedCategory = category?.toLowerCase() || 'default';
  const images = foodImages[normalizedCategory] || foodImages.default;
  const randomIndex = Math.floor(Math.random() * images.length);
  return images[randomIndex];
};

// Function to get a consistent image for a recipe (based on recipe title hash)
export const getFoodImageForRecipe = (recipe) => {
  if (recipe.media?.mainImage) {
    return recipe.media.mainImage;
  }
  
  const category = recipe.categories?.[0] || 'default';
  const normalizedCategory = category.toLowerCase();
  const images = foodImages[normalizedCategory] || foodImages.default;
  
  // Create a simple hash from recipe title for consistency
  let hash = 0;
  const title = recipe.title || '';
  for (let i = 0; i < title.length; i++) {
    const char = title.charCodeAt(i);
    hash = ((hash << 5) - hash) + char;
    hash = hash & hash; // Convert to 32-bit integer
  }
  
  const index = Math.abs(hash) % images.length;
  return images[index];
};

export default { foodImages, getRandomFoodImage, getFoodImageForRecipe };